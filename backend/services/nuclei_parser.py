"""
DRISHTI — Phase 10 ProjectDiscovery Nuclei Output Parser & Evidence Sanitizer
Parses streaming or batched JSONL output defensively into typed NucleiFindingObservation records.

Data Quality & Security Controls:
1. Redacts sensitive credentials (Authorization headers, API keys, session tokens, passwords).
2. Defensive bounds: caps captured evidence length and maximum records per scan.
3. Resilient line parsing: ignores malformed or non-JSON lines without dropping valid findings.
4. Normalizes severities to standard DRISHTI vocabulary (info, low, medium, high, critical, unknown).
5. Extracts CVE, CWE, CVSS score, tags, and matcher evidence safely without inventing missing values.
"""

from datetime import datetime, timezone
import json
import logging
import re
from typing import Any, Dict, List, Optional, Tuple
from urllib.parse import urlparse

from backend.services.scanner_foundation import NucleiFindingObservation
from backend.services.scope import is_in_scope, normalize_domain

logger = logging.getLogger("drishti.nuclei_parser")

MAX_EVIDENCE_LENGTH = 4096
MAX_PARSED_FINDINGS = 2000

# Regex patterns for sanitizing credentials in evidence, curl commands, and outputs
SENSITIVE_PATTERNS = [
    (re.compile(r"(?i)(authorization:\s*bearer\s+)[^\r\n&]+"), r"\1[REDACTED]"),
    (re.compile(r"(?i)(authorization:\s*basic\s+)[^\r\n&]+"), r"\1[REDACTED]"),
    (re.compile(r"(?i)(api[-_]?key\s*[:=]\s*)[^\r\n&,;\"'\s]+"), r"\1[REDACTED]"),
    (re.compile(r"(?i)(password\s*[:=]\s*)[^\r\n&,;\"'\s]+"), r"\1[REDACTED]"),
    (re.compile(r"(?i)(secret\s*[:=]\s*)[^\r\n&,;\"'\s]+"), r"\1[REDACTED]"),
    (re.compile(r"(?i)(token\s*[:=]\s*)[^\r\n&,;\"'\s]+"), r"\1[REDACTED]"),
    (re.compile(r"(?i)(cookie:\s*)[^\r\n]+"), r"\1[REDACTED]"),
    (re.compile(r"(?i)(set-cookie:\s*)[^\r\n]+"), r"\1[REDACTED]"),
]

VALID_SEVERITIES = {"info", "low", "medium", "high", "critical", "unknown"}


def sanitize_evidence(text: Optional[str]) -> Optional[str]:
    """Redacts secrets, auth headers, and session tokens from evidence snippets."""
    if not text:
        return None
    sanitized = text
    for pattern, replacement in SENSITIVE_PATTERNS:
        sanitized = pattern.sub(replacement, sanitized)
    if len(sanitized) > MAX_EVIDENCE_LENGTH:
        sanitized = sanitized[:MAX_EVIDENCE_LENGTH] + "\n...[TRUNCATED BY POLICY]"
    return sanitized


def normalize_severity(raw_severity: Optional[str]) -> str:
    """Normalizes raw severity string from Nuclei JSON to standard vocabulary."""
    if not raw_severity:
        return "unknown"
    clean = str(raw_severity).strip().lower()
    if clean in VALID_SEVERITIES:
        return clean
    return "unknown"


def parse_matched_target(matched_at: str) -> Tuple[str, int, str]:
    """
    Extracts host, port, and scheme from Nuclei's matched-at URL or host string.
    Returns (host, port, scheme).
    """
    if not matched_at:
        return "unknown", 80, "http"

    matched = matched_at.strip()
    if not matched.startswith("http://") and not matched.startswith("https://"):
        matched = "http://" + matched

    try:
        parsed = urlparse(matched)
        host = parsed.hostname or "unknown"
        scheme = parsed.scheme.lower() if parsed.scheme else "http"
        port = parsed.port
        if not port:
            port = 443 if scheme == "https" else 80
        return host, port, scheme
    except Exception:
        return "unknown", 80, "http"


def parse_nuclei_jsonl(
    raw_jsonl: str,
    scanner_version: Optional[str] = None,
    authorized_domain: Optional[str] = None,
) -> List[NucleiFindingObservation]:
    """
    Parses newline-delimited JSON (JSONL) records generated by Nuclei.
    Filters out any out-of-scope targets if authorized_domain is provided.
    Deduplicates findings based on (template_id, matched_at, matcher_name).
    """
    if not raw_jsonl or not raw_jsonl.strip():
        return []

    observations: List[NucleiFindingObservation] = []
    seen_keys = set()

    for line in raw_jsonl.splitlines():
        line = line.strip()
        if not line:
            continue
        if len(observations) >= MAX_PARSED_FINDINGS:
            logger.warning("Reached maximum allowed Nuclei observations limit (%d)", MAX_PARSED_FINDINGS)
            break

        try:
            record = json.loads(line)
        except (json.JSONDecodeError, ValueError):
            # Gracefully ignore non-JSON or banner log lines
            continue

        if not isinstance(record, dict) or not record:
            continue

        template_id = record.get("template-id") or record.get("template_id") or record.get("templateID")
        if not template_id:
            # Not a finding record (e.g. status heartbeat or blank object)
            continue
        template_id = str(template_id)
        info = record.get("info") if isinstance(record.get("info"), dict) else {}
        template_name = str(info.get("name") or record.get("template-name") or template_id)
        raw_sev = info.get("severity") or record.get("severity")
        severity = normalize_severity(raw_sev)

        matched_at = str(record.get("matched-at") or record.get("matched") or record.get("host") or "")
        host, port, scheme = parse_matched_target(matched_at)

        # Enforce scope check against authorized domain if specified
        if authorized_domain and host != "unknown":
            try:
                if not is_in_scope(host, authorized_domain):
                    logger.warning("Dropping Nuclei finding for out-of-scope host: %s (authorized: %s)", host, authorized_domain)
                    continue
            except Exception:
                continue

        matcher_name = record.get("matcher-name") or record.get("matcher_name")
        if matcher_name:
            matcher_name = str(matcher_name)

        # Deduplication key
        dedup_key = (template_id, matched_at, matcher_name)
        if dedup_key in seen_keys:
            continue
        seen_keys.add(dedup_key)

        # Extract classification info
        classification = info.get("classification") if isinstance(info.get("classification"), dict) else {}
        cve_id = None
        cve_list = classification.get("cve-id") or classification.get("cve_id")
        if isinstance(cve_list, list) and cve_list:
            cve_id = str(cve_list[0])
        elif isinstance(cve_list, str):
            cve_id = cve_list

        cwe_id = None
        cwe_list = classification.get("cwe-id") or classification.get("cwe_id")
        if isinstance(cwe_list, list) and cwe_list:
            cwe_id = str(cwe_list[0])
        elif isinstance(cwe_list, str):
            cwe_id = cwe_list

        cvss_score = None
        raw_cvss = classification.get("cvss-score") or classification.get("cvss_score")
        if raw_cvss is not None:
            try:
                cvss_score = float(raw_cvss)
            except (ValueError, TypeError):
                pass

        # Reference links
        ref_raw = info.get("reference")
        reference_urls: List[str] = []
        if isinstance(ref_raw, list):
            reference_urls = [str(r) for r in ref_raw if isinstance(r, str)]
        elif isinstance(ref_raw, str):
            reference_urls = [ref_raw]

        # Tags
        tags_raw = info.get("tags")
        tag_list: List[str] = []
        if isinstance(tags_raw, list):
            tag_list = [str(t) for t in tags_raw if isinstance(t, str)]
        elif isinstance(tags_raw, str):
            tag_list = [t.strip() for t in tags_raw.split(",") if t.strip()]

        # Extracted results
        extracted_raw = record.get("extracted-results") or record.get("extracted_results")
        extracted_results: List[str] = []
        if isinstance(extracted_raw, list):
            extracted_results = [str(x) for x in extracted_raw if isinstance(x, str)]
        elif isinstance(extracted_raw, str):
            extracted_results = [extracted_raw]

        # Description & Remediation
        description = info.get("description") or None
        remediation = info.get("remediation") or None

        # Evidence & Curl Command
        curl_command = sanitize_evidence(record.get("curl-command") or record.get("curl_command"))
        evidence = None
        if extracted_results:
            evidence = sanitize_evidence("\n".join(extracted_results))
        elif record.get("response"):
            evidence = sanitize_evidence(str(record.get("response")))
        elif record.get("request"):
            evidence = sanitize_evidence(str(record.get("request")))

        type_field = str(record.get("type") or "http")

        obs = NucleiFindingObservation(
            template_id=template_id,
            template_name=template_name,
            severity=severity,
            matched_at=matched_at or host,
            host=host,
            port=port,
            scheme=scheme,
            url=matched_at if matched_at.startswith("http") else None,
            matcher_name=matcher_name,
            extracted_results=extracted_results,
            type=type_field,
            description=str(description) if description else None,
            remediation=str(remediation) if remediation else None,
            reference=reference_urls,
            tags=tag_list,
            cve_id=cve_id,
            cwe_id=cwe_id,
            cvss_score=cvss_score,
            curl_command=curl_command,
            evidence=evidence,
            confidence="TENTATIVE",
            scanner_name="ProjectDiscovery Nuclei",
            scanner_version=scanner_version,
            observed_at=datetime.now(timezone.utc),
        )
        observations.append(obs)

    return observations
