class GeminiAdapter(BaseLLMAdapter):
    provider = LLMProvider.GEMINI
    model_name = "gemini-1.5-flash"

    async def generate(self, request: LLMRequest, api_key: str) -> str:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model_name}:generateContent?key={api_key}"
        parts = []
        if request.system_instruction:
            parts.append({"text": f"System Directive:\n{request.system_instruction}\n"})
        parts.append({"text": request.prompt})

        payload = {
            "contents": [{"parts": parts}],
            "generationConfig": {
                "temperature": request.temperature,
                "maxOutputTokens": request.max_tokens,
            }
        }

        async with httpx.AsyncClient(timeout=20.0) as client:
            resp = await client.post(url, json=payload)
            resp.raise_for_status()
            data = resp.json()
            candidates = data.get("candidates", [])
            if candidates:
                return candidates[0]["content"]["parts"][0]["text"]
            raise ValueError("No candidate output generated by Gemini API.")


class HuggingFaceAdapter(BaseLLMAdapter):
    provider = LLMProvider.HUGGINGFACE
    model_name = "meta-llama/Meta-Llama-3-8B-Instruct"

    async def generate(self, request: LLMRequest, api_key: str) -> str:
        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        }
        prompt_full = f"{request.system_instruction}\n\n{request.prompt}" if request.system_instruction else request.prompt
        payload = {
            "inputs": prompt_full,
            "parameters": {
                "max_new_tokens": request.max_tokens,
                "temperature": max(0.1, request.temperature),
            }
        }
        async with httpx.AsyncClient(timeout=20.0) as client:
            resp = await client.post(f"https://api-inference.huggingface.co/models/{self.model_name}", headers=headers, json=payload)
            resp.raise_for_status()
            data = resp.json()
            if isinstance(data, list) and len(data) > 0:
                return data[0].get("generated_text", str(data[0]))
            return str(data)


