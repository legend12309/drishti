class LLMRouter:
    def __init__(self):
        self.adapters: Dict[LLMProvider, BaseLLMAdapter] = {
            LLMProvider.GROQ: GroqAdapter(),
            LLMProvider.NVIDIA: NvidiaAdapter(),
            LLMProvider.GEMINI: GeminiAdapter(),
            LLMProvider.HUGGINGFACE: HuggingFaceAdapter(),
            LLMProvider.OFFLINE_SYNTHETIC: OfflineSyntheticAdapter(),
        }

        # Priority fallback chain strictly among the four supported providers + offline synthetic
        self.default_priority = [
            LLMProvider.GROQ,
            LLMProvider.NVIDIA,
            LLMProvider.GEMINI,
            LLMProvider.HUGGINGFACE,
            LLMProvider.OFFLINE_SYNTHETIC,
        ]

    def get_api_key(self, provider: LLMProvider) -> str:
        key_map = {
            LLMProvider.GROQ: os.getenv("GROQ_API_KEY", ""),
            LLMProvider.NVIDIA: os.getenv("NVIDIA_API_KEY", ""),
            LLMProvider.GEMINI: os.getenv("GEMINI_API_KEY", ""),
            LLMProvider.HUGGINGFACE: os.getenv("HUGGINGFACE_API_KEY", os.getenv("HF_TOKEN", "")),
            LLMProvider.OFFLINE_SYNTHETIC: "synthetic",
        }
        return key_map.get(provider, "")

    def is_provider_available(self, provider: LLMProvider) -> bool:
        if provider == LLMProvider.OFFLINE_SYNTHETIC:
            return True
        key = self.get_api_key(provider)
        return bool(key and not key.startswith("  "))

    async def generate_with_fallback(
        self,
        request: LLMRequest,
        provider_override: Optional[LLMProvider] = None,
    ) -> LLMResponse:
        """
        Executes generation through the designated provider, automatically falling back
        to secondary configured providers upon error or rate-limiting.
        """
        t0 = time.perf_counter()
        fallback_history: List[str] = []

        # Determine attempt sequence
        if provider_override and provider_override in self.adapters:
            providers_to_try = [provider_override] + [p for p in self.default_priority if p != provider_override]
        else:
            providers_to_try = list(self.default_priority)

        # Filter only available providers (and always keep OfflineSynthetic as final safety net)
        active_chain = [p for p in providers_to_try if self.is_provider_available(p)]
        if LLMProvider.OFFLINE_SYNTHETIC not in active_chain:
            active_chain.append(LLMProvider.OFFLINE_SYNTHETIC)

        attempts = 0
        for provider in active_chain:
            adapter = self.adapters[provider]
            api_key = self.get_api_key(provider)
            attempts += 1

            # If dummy mock key in dev, route safely to offline synthetic to prevent cloud 401 errors
            if "test" in api_key.lower() and provider != LLMProvider.OFFLINE_SYNTHETIC:
                fallback_history.append(f"{provider.value}: test_api_key_bypassed_to_synthetic")
                continue

            try:
                text = await adapter.generate(request, api_key)
                elapsed_ms = round((time.perf_counter() - t0) * 1000, 2)
                return LLMResponse(
                    text=text,
                    provider_used=provider,
                    model_name=adapter.model_name,
                    fallback_attempts=attempts - 1,
                    fallback_history=fallback_history,
                    latency_ms=elapsed_ms,
                    is_fallback=(attempts > 1),
                    evidence_grounding_score=1.0,
                )
            except Exception as ex:
                err_desc = f"{provider.value}: {str(ex)[:120]}"
                fallback_history.append(err_desc)

        # Final guarantee fallback
        synth_adapter = self.adapters[LLMProvider.OFFLINE_SYNTHETIC]
        text = await synth_adapter.generate(request, "")
        elapsed_ms = round((time.perf_counter() - t0) * 1000, 2)
        return LLMResponse(
            text=text,
            provider_used=LLMProvider.OFFLINE_SYNTHETIC,
            model_name=synth_adapter.model_name,
            fallback_attempts=attempts,
            fallback_history=fallback_history,
            latency_ms=elapsed_ms,
            is_fallback=True,
            evidence_grounding_score=1.0,
        )


# Global singleton instance
llm_router = LLMRouter()
